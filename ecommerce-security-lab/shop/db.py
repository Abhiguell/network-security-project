"""
shop/db.py: SQLite database for the LabMart store.

All SQL uses "?" placeholders, so user input can never change a query
(protection against SQL injection).

Important column: users.is_synthetic / orders.is_synthetic
  1 = fictional test record generated by seed.py (the ONLY data the lab may read)
  0 = a real account created through the website (never exposed to the lab)
"""
import sqlite3
from datetime import datetime

from flask import current_app, g

TS_FORMAT = "%Y-%m-%d %H:%M:%S"

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    username        TEXT UNIQUE NOT NULL,
    email           TEXT UNIQUE NOT NULL,
    password_hash   TEXT NOT NULL,
    full_name       TEXT DEFAULT '',
    phone           TEXT DEFAULT '',
    address         TEXT DEFAULT '',
    city            TEXT DEFAULT '',
    role            TEXT NOT NULL DEFAULT 'customer',     -- customer | admin
    is_active       INTEGER NOT NULL DEFAULT 1,
    is_synthetic    INTEGER NOT NULL DEFAULT 0,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until    TEXT,
    created_at      TEXT NOT NULL,
    last_login      TEXT
);

CREATE TABLE IF NOT EXISTS products (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    sku         TEXT UNIQUE NOT NULL,
    name        TEXT NOT NULL,
    category    TEXT NOT NULL,
    description TEXT NOT NULL,
    price       INTEGER NOT NULL,           -- Rupiah, whole numbers (Midtrans needs integers)
    stock       INTEGER NOT NULL,
    emoji       TEXT NOT NULL,
    color       TEXT NOT NULL,
    is_active   INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS orders (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    order_code       TEXT UNIQUE NOT NULL,
    user_id          INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status           TEXT NOT NULL DEFAULT 'pending',   -- pending | paid | failed | cancelled
    payment_method   TEXT NOT NULL,                     -- midtrans | demo
    payment_status   TEXT DEFAULT '',                   -- raw status from the gateway
    total            INTEGER NOT NULL,
    shipping_name    TEXT NOT NULL,
    shipping_phone   TEXT NOT NULL,
    shipping_address TEXT NOT NULL,
    is_synthetic     INTEGER NOT NULL DEFAULT 0,
    created_at       TEXT NOT NULL,
    paid_at          TEXT
);

CREATE TABLE IF NOT EXISTS order_items (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    order_id   INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL,
    name       TEXT NOT NULL,
    price      INTEGER NOT NULL,
    qty        INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS security_events (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    ts           TEXT NOT NULL,
    severity     TEXT NOT NULL,                -- info | low | medium | high | critical
    category     TEXT NOT NULL,
    message      TEXT NOT NULL,
    ip           TEXT,
    username     TEXT,
    details      TEXT,
    source       TEXT NOT NULL DEFAULT 'web',  -- web | simulation
    acknowledged INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS incidents (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    ts          TEXT NOT NULL,
    kind        TEXT NOT NULL,                 -- spyware | ransomware | trojan
    severity    TEXT NOT NULL,
    title       TEXT NOT NULL,
    details     TEXT,
    operator    TEXT,
    status      TEXT NOT NULL DEFAULT 'open',  -- open | resolved
    resolved_at TEXT
);

CREATE TABLE IF NOT EXISTS activity_log (
    id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, user_id INTEGER, username TEXT,
    ip TEXT, method TEXT, path TEXT, status INTEGER, user_agent TEXT
);

CREATE TABLE IF NOT EXISTS login_attempts (
    id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT NOT NULL, username TEXT, ip TEXT, success INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS sim_traffic (
    id       INTEGER PRIMARY KEY AUTOINCREMENT,
    ts       TEXT NOT NULL,
    ip       TEXT,
    module   TEXT,
    kind     TEXT,
    bot_id   TEXT,
    seq      INTEGER,
    bytes    INTEGER,
    operator TEXT,
    detail   TEXT
);

CREATE TABLE IF NOT EXISTS api_nonces (
    nonce TEXT PRIMARY KEY,
    ts    REAL NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_events_ts ON security_events(ts);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);
"""


def now_str():
    return datetime.now().strftime(TS_FORMAT)


def get_db():
    if "db" not in g:
        g.db = sqlite3.connect(current_app.config["DATABASE"], timeout=10)
        g.db.row_factory = sqlite3.Row
        g.db.execute("PRAGMA foreign_keys = ON")
    return g.db


def close_db(_e=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def query(sql, args=(), one=False):
    rows = get_db().execute(sql, args).fetchall()
    return (rows[0] if rows else None) if one else rows


def execute(sql, args=()):
    db = get_db()
    cur = db.execute(sql, args)
    db.commit()
    return cur.lastrowid


def get_setting(key, default=None):
    row = query("SELECT value FROM settings WHERE key = ?", (key,), one=True)
    return row["value"] if row else default


def set_setting(key, value):
    execute("INSERT INTO settings (key, value) VALUES (?, ?) "
            "ON CONFLICT(key) DO UPDATE SET value = excluded.value", (key, str(value)))


def init_app(app):
    app.teardown_appcontext(close_db)
    with app.app_context():
        db = get_db()
        db.execute("PRAGMA journal_mode = WAL")      # lets the lab's API calls and page loads overlap
        db.executescript(SCHEMA)
        from .seed import seed
        seed(app)
